#!/bin/bash

# Скрипт для запуска тестов PHPUnit

echo "========================================"
echo "Запуск PHPUnit тестов"
echo "========================================"
echo ""

# Проверка наличия vendor
if [ ! -d "vendor" ]; then
    echo "Установка зависимостей..."
    composer install
    echo ""
fi

# Запуск тестов
echo "Запуск тестов..."
vendor/bin/phpunit --colors=always

echo ""
echo "========================================"
echo "Тесты завершены"
echo "========================================"
